"""Synthetic notes, for trying the app and testing it without a guitar.

A crude plucked string (decaying partials, brighter at the start) is passed
through a soft asymmetric clipper whose drive rises geometrically with the
gain setting, as an audio-taper gain pot does. The same plucks are reused at
every setting, so the only thing that changes between settings is the drive.

These notes are labelled as synthetic everywhere they appear. They show what
the app does; they say nothing about any real pedal.
"""
from __future__ import annotations

import cmath
import math
import random

from .measure import measure
from .store import Store
from .wav import write_wav

SAMPLE_RATE = 48_000
DEMO_PEDAL = "Synthetic demo pedal"
DEMO_LABEL = "A2 (synthetic)"


def pluck(f0: float = 110.0, duration: float = 1.0, sample_rate: int = SAMPLE_RATE,
          pluck_position: float = 0.22, pre_roll: float = 0.1,
          rng: random.Random | None = None) -> list[float]:
    """A plucked-string note after ``pre_roll`` seconds of silence, peak 1."""
    rng = rng or random.Random()
    n = int(duration * sample_rate)
    start = int(pre_roll * sample_rate)
    y = [0.0] * n
    for k in range(1, 30):
        freq = k * f0 * math.sqrt(1 + 3e-5 * k * k)        # slightly sharp, as a stiff string is
        if freq > 0.45 * sample_rate:
            break
        amplitude = abs(math.sin(k * math.pi * pluck_position)) / k
        decay = math.exp(-1.0 / ((1.2 / k ** 0.9) * sample_rate))
        # Rotate a phasor rather than calling sin() for every sample.
        step = cmath.exp(2j * math.pi * freq / sample_rate) * decay
        z = amplitude * cmath.exp(1j * rng.uniform(0, 2 * math.pi))
        for i in range(start, n):
            y[i] += z.imag
            z *= step
    attack = int(0.002 * sample_rate)
    for i in range(attack):
        y[start + i] *= 0.5 - 0.5 * math.cos(math.pi * i / attack)
    release = int(0.03 * sample_rate)
    for i in range(release):
        y[n - release + i] *= 0.5 + 0.5 * math.cos(math.pi * i / release)
    peak = max(abs(v) for v in y)
    return [v / peak for v in y]


def drive_for_setting(setting: float, top: float = 10.0, drive_max: float = 80.0) -> float:
    """Knob 0..top maps geometrically onto a drive of 1..drive_max."""
    return drive_max ** (setting / top)


def clipper(x: list[float], drive: float, asymmetry: float = 0.85,
            out_peak: float = 10 ** (-12 / 20)) -> list[float]:
    """Soft clipping, gentler on the negative side, then a fixed output peak
    (as if the pedal's level knob were set to match loudness)."""
    y = [math.tanh(drive * v) if v >= 0 else asymmetry * math.tanh(drive * v / asymmetry)
         for v in x]
    peak = max(abs(v) for v in y)
    return [v / peak * out_peak for v in y]


def add_demo_notes(store: Store, plucks: int = 3, settings: range = range(11),
                   seed: int = 20261027) -> str:
    rng = random.Random(seed)
    takes = []
    for _ in range(plucks):
        level = 10 ** ((-12 + rng.gauss(0, 1.0)) / 20)
        note = pluck(f0=110.0 * 2 ** (rng.gauss(0, 3) / 1200),
                     pluck_position=min(0.4, max(0.1, rng.gauss(0.22, 0.02))), rng=rng)
        takes.append([level * v for v in note])
    for setting in settings:
        for take in takes:
            out = clipper(take, drive_for_setting(setting))
            out = [v + rng.gauss(0, 10 ** (-90 / 20)) for v in out]   # a little converter noise
            m, _ = measure(out, SAMPLE_RATE)
            store.add(pedal=DEMO_PEDAL, gain=float(setting), label=DEMO_LABEL,
                      comment="Synthetic: generated by guitarnote.demo, not a recording.",
                      source="synthetic", wav=write_wav(out, SAMPLE_RATE), m=m)
    return DEMO_PEDAL
